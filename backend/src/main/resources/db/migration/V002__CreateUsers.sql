-- Autenticação PROVISÓRIA, exclusivamente para desenvolvimento/testes.
-- Não publicar estas credenciais em produção. Substituir os valores de
-- password_hash por hashes BCrypt quando Spring Security for implementado.
CREATE TABLE usuario (
    id_usuario    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(200) NOT NULL,
    email         VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20) NOT NULL,
    ativo         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_role CHECK (role IN ('ADMIN', 'CURATOR', 'USER')),
    CONSTRAINT ck_usuario_email_normalizado CHECK (email = LOWER(TRIM(email)))
);

COMMENT ON COLUMN usuario.password_hash IS
    'PROVISÓRIO: senha em texto simples para desenvolvimento/testes. Substituir por BCrypt antes de produção.';

