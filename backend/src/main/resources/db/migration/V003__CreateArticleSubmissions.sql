-- Área de trabalho de curadoria: não publica dados em fonte/ocorrencia.
CREATE TABLE submissao_artigo (
    id_submissao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario),
    titulo VARCHAR(500) NOT NULL,
    link_original VARCHAR(1000) NOT NULL,
    pdf_path VARCHAR(100) NOT NULL,
    pdf_nome VARCHAR(255) NOT NULL,
    pdf_tamanho BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    ano INTEGER,
    doenca VARCHAR(200),
    dados_usuario JSONB NOT NULL,
    dados_llm JSONB,
    dados_curados JSONB,
    extraction_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    extracted_at TIMESTAMPTZ,
    extraction_model VARCHAR(100),
    extraction_mock BOOLEAN NOT NULL DEFAULT FALSE,
    id_curador INTEGER REFERENCES usuario(id_usuario),
    reviewed_at TIMESTAMPTZ,
    rejection_reason VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_submissao_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_submissao_extraction CHECK (extraction_status IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_submissao_ano CHECK (ano BETWEEN 1500 AND 2100),
    CONSTRAINT ck_submissao_pdf_tamanho CHECK (pdf_tamanho > 0 AND pdf_tamanho <= 20971520),
    CONSTRAINT ck_submissao_dados_usuario CHECK (jsonb_typeof(dados_usuario) = 'object'),
    CONSTRAINT ck_submissao_dados_llm CHECK (dados_llm IS NULL OR jsonb_typeof(dados_llm) = 'object'),
    CONSTRAINT ck_submissao_dados_curados CHECK (dados_curados IS NULL OR jsonb_typeof(dados_curados) = 'object'),
    CONSTRAINT ck_submissao_decisao CHECK (
        (status = 'PENDING' AND id_curador IS NULL AND reviewed_at IS NULL AND rejection_reason IS NULL AND dados_curados IS NULL)
        OR (status = 'APPROVED' AND id_curador IS NOT NULL AND reviewed_at IS NOT NULL AND dados_curados IS NOT NULL AND rejection_reason IS NULL)
        OR (status = 'REJECTED' AND id_curador IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NOT NULL AND LENGTH(TRIM(rejection_reason)) > 0)
    )
);
CREATE INDEX idx_submissao_usuario_data ON submissao_artigo (id_usuario, created_at DESC);
CREATE INDEX idx_submissao_status_data ON submissao_artigo (status, created_at DESC);
CREATE INDEX idx_submissao_ano ON submissao_artigo (ano);
CREATE INDEX idx_submissao_doenca ON submissao_artigo (doenca);
COMMENT ON TABLE submissao_artigo IS
    'Curadoria independente das tabelas definitivas. IDs de atores informados pelo frontend são provisórios, sem autenticação real.';
COMMENT ON COLUMN submissao_artigo.pdf_path IS 'Chave relativa no storage, nunca caminho absoluto da máquina.';
COMMENT ON COLUMN submissao_artigo.dados_llm IS 'Resultado separado dos dados do usuário; extraction_mock identifica extração simulada.';
