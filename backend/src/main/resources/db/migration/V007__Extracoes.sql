-- Extrações automáticas (pipeline de LLM) entram como submissões e suas ocorrências
-- aparecem no mapa como NÃO CURADAS até que um curador humano decida.
-- As tabelas normalizadas (ocorrencia, doenca, parasito...) não recebem texto bruto da LLM.

-- 1. Submissões passam a ter origem; extrações não têm PDF nem link obrigatórios.
ALTER TABLE submissao_artigo ADD COLUMN origem VARCHAR(20) NOT NULL DEFAULT 'USUARIO';
ALTER TABLE submissao_artigo ADD CONSTRAINT ck_submissao_origem CHECK (origem IN ('USUARIO', 'EXTRACAO'));
ALTER TABLE submissao_artigo ALTER COLUMN link_original DROP NOT NULL;
ALTER TABLE submissao_artigo ALTER COLUMN pdf_path DROP NOT NULL;
ALTER TABLE submissao_artigo ALTER COLUMN pdf_nome DROP NOT NULL;
ALTER TABLE submissao_artigo ALTER COLUMN pdf_tamanho DROP NOT NULL;
ALTER TABLE submissao_artigo ADD CONSTRAINT ck_submissao_arquivos_usuario CHECK (
    origem <> 'USUARIO'
    OR (link_original IS NOT NULL AND pdf_path IS NOT NULL AND pdf_nome IS NOT NULL AND pdf_tamanho IS NOT NULL)
);
CREATE INDEX idx_submissao_origem ON submissao_artigo (origem, status);

-- 2. Autor técnico das extrações: não é uma pessoa e não entra no sistema.
INSERT INTO usuario (nome, email, role, ativo)
SELECT 'Pipeline de extração', 'pipeline@sidpb.invalid', 'USER', FALSE
WHERE NOT EXISTS (SELECT 1 FROM usuario WHERE email = 'pipeline@sidpb.invalid');

-- 3. Uma extração por artigo, guardada exatamente como chegou.
CREATE TABLE extracao (
    id_extracao        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_submissao       INTEGER NOT NULL UNIQUE REFERENCES submissao_artigo (id_submissao) ON DELETE CASCADE,
    id_externo         VARCHAR(500) NOT NULL UNIQUE,
    modelo             VARCHAR(200),
    qualidade          VARCHAR(10) NOT NULL,
    ocorrencias_lidas  INTEGER NOT NULL DEFAULT 0,
    observacao_leitura VARCHAR(1000),
    conteudo_bruto     TEXT NOT NULL,
    recebida_em        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_extracao_qualidade CHECK (qualidade IN ('VALIDA', 'PARCIAL', 'ILEGIVEL'))
);
COMMENT ON COLUMN extracao.qualidade IS
    'Leitura automática e determinística do JSON (forma, não conteúdo): VALIDA, PARCIAL (parte recuperada) ou ILEGIVEL.';
COMMENT ON COLUMN extracao.id_externo IS 'Identificador enviado pelo pipeline; reenvios com o mesmo id não duplicam.';

-- 4. Ocorrências extraídas: textos da LLM, local resolvido pelo IBGE e o que não cabe no esquema em "outros".
CREATE TABLE ocorrencia_extraida (
    id_ocorrencia_extraida INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_extracao            INTEGER NOT NULL REFERENCES extracao (id_extracao) ON DELETE CASCADE,
    ordem                  INTEGER NOT NULL,
    status_curadoria       VARCHAR(12) NOT NULL DEFAULT 'NAO_CURADA',
    doenca                 VARCHAR(300),
    doenca_original        VARCHAR(300),
    parasito               VARCHAR(300),
    vetor                  VARCHAR(300),
    hospedeiro             VARCHAR(300),
    categoria_hospedeiro   VARCHAR(100),
    local_texto            VARCHAR(1000),
    municipio_texto        VARCHAR(300),
    uf_texto               VARCHAR(100),
    id_municipio           INTEGER REFERENCES municipio (id_municipio),
    id_estado              INTEGER REFERENCES estado (id_estado),
    latitude               NUMERIC(10,7),
    longitude              NUMERIC(10,7),
    precisao_local         VARCHAR(10) NOT NULL,
    ano                    INTEGER,
    outros                 JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT uq_ocorrencia_extraida_ordem UNIQUE (id_extracao, ordem),
    CONSTRAINT ck_ocorrencia_extraida_status CHECK (status_curadoria IN ('NAO_CURADA', 'CURADA', 'REPROVADA')),
    CONSTRAINT ck_ocorrencia_extraida_precisao CHECK (precisao_local IN ('EXATA', 'MUNICIPIO', 'ESTADO', 'SEM_LOCAL')),
    CONSTRAINT ck_ocorrencia_extraida_coordenadas CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CONSTRAINT ck_ocorrencia_extraida_outros CHECK (jsonb_typeof(outros) = 'object')
);
COMMENT ON COLUMN ocorrencia_extraida.precisao_local IS
    'EXATA (coordenada informada), MUNICIPIO (centro do município), ESTADO (sem ponto no mapa) ou SEM_LOCAL.';
COMMENT ON COLUMN ocorrencia_extraida.outros IS
    'Informações fora do esquema: parte do corpo, tratamento, desfecho, quantidade, evidências com página etc.';
CREATE INDEX idx_ocorrencia_extraida_status ON ocorrencia_extraida (status_curadoria);
CREATE INDEX idx_ocorrencia_extraida_municipio ON ocorrencia_extraida (id_municipio);
